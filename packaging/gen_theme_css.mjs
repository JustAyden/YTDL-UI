// Bake the default theme (seed #22d3ee, tonal spot, 2025 spec) into static/css/theme.css so the
// first page load has the right colors before any JavaScript runs.
//   node packaging/gen_theme_css.mjs
import { writeFileSync } from "node:fs";
import { DEFAULT_SEED, DEFAULT_STYLE, themeCss } from "../static/js/theme.js";

const css = themeCss(DEFAULT_SEED, DEFAULT_STYLE, "standard")
  .replace(/;/g, ";\n  ").replace(/\{/g, " {\n  ").replace(/\}/g, "\n}\n");
writeFileSync(new URL("../static/css/theme.css", import.meta.url),
  `/* Generated by packaging/gen_theme_css.mjs — Material 3 (2025 spec) colors for seed ${DEFAULT_SEED}. */\n${css}`);
console.log("wrote static/css/theme.css");
